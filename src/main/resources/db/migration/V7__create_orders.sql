CREATE TABLE noghterangi.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(64) NOT NULL,
    customer_name VARCHAR(160) NOT NULL CHECK (length(btrim(customer_name)) > 0),
    phone VARCHAR(11) NOT NULL CHECK (phone ~ '^09[0-9]{9}$'),
    delivery_area VARCHAR(160) NOT NULL CHECK (length(btrim(delivery_area)) > 0),
    delivery_address VARCHAR(1000) NOT NULL CHECK (length(btrim(delivery_address)) > 0),
    customer_note VARCHAR(1000),
    total_amount BIGINT NOT NULL CHECK (total_amount >= 0),
    status VARCHAR(32) NOT NULL CHECK (status IN ('WAITING_FOR_PAYMENT', 'PAID', 'PREPARING', 'READY', 'DELIVERED', 'CANCELLED')),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_orders_order_number UNIQUE (order_number)
);
-- The unique constraint already indexes order_number.
CREATE INDEX idx_orders_status ON noghterangi.orders(status);
CREATE INDEX idx_orders_created_at ON noghterangi.orders(created_at);

CREATE TABLE noghterangi.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES noghterangi.orders(id),
    -- No FK to product: historical name/price snapshots must survive product deletion.
    product_id BIGINT NOT NULL CHECK (product_id > 0),
    product_name VARCHAR(160) NOT NULL CHECK (length(btrim(product_name)) > 0),
    unit_price BIGINT NOT NULL CHECK (unit_price >= 0),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    line_total BIGINT NOT NULL CHECK (line_total >= 0 AND line_total = unit_price::numeric * quantity)
);
CREATE INDEX idx_order_items_order ON noghterangi.order_items(order_id);

CREATE TABLE noghterangi.product (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    slug VARCHAR(160) NOT NULL,
    sku VARCHAR(64) NOT NULL,
    brand VARCHAR(120),
    short_description VARCHAR(500),
    description TEXT,
    price BIGINT NOT NULL,
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    featured BOOLEAN NOT NULL DEFAULT FALSE,
    display_order INTEGER NOT NULL DEFAULT 0,
    category_id BIGINT NOT NULL,
    type VARCHAR(32) NOT NULL,
    minimum_age INTEGER,
    maximum_age INTEGER,
    minimum_players INTEGER,
    maximum_players INTEGER,
    playing_time_minutes INTEGER,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_product_category FOREIGN KEY (category_id) REFERENCES noghterangi.category(id),
    CONSTRAINT uk_product_slug UNIQUE (slug),
    CONSTRAINT uk_product_sku UNIQUE (sku),
    CONSTRAINT ck_product_name CHECK (length(btrim(name)) > 0),
    CONSTRAINT ck_product_slug CHECK (slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT ck_product_sku CHECK (length(btrim(sku)) > 0 AND sku = upper(btrim(sku))),
    CONSTRAINT ck_product_price CHECK (price >= 0),
    CONSTRAINT ck_product_stock CHECK (stock_quantity >= 0),
    CONSTRAINT ck_product_display_order CHECK (display_order >= 0),
    CONSTRAINT ck_product_type CHECK (type IN ('STATIONERY', 'EDUCATIONAL', 'BOARD_GAME', 'BOOK', 'OTHER')),
    CONSTRAINT ck_product_description CHECK (length(description) <= 10000),
    CONSTRAINT ck_product_age CHECK (minimum_age >= 0 AND maximum_age >= 0 AND maximum_age >= minimum_age),
    CONSTRAINT ck_product_players CHECK (minimum_players > 0 AND maximum_players > 0 AND maximum_players >= minimum_players),
    CONSTRAINT ck_product_playing_time CHECK (playing_time_minutes > 0),
    CONSTRAINT ck_product_game_fields CHECK (type = 'BOARD_GAME' OR
        (minimum_age IS NULL AND maximum_age IS NULL AND minimum_players IS NULL
         AND maximum_players IS NULL AND playing_time_minutes IS NULL))
);

-- PostgreSQL does not create indexes on referencing foreign-key columns.
CREATE INDEX idx_product_category ON noghterangi.product(category_id);
